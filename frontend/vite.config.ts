import tailwindcss from "@tailwindcss/vite";
import react from "@vitejs/plugin-react";
import { defineConfig } from "vite";

// In development the React app runs on :5173 and the Python backend on :8000.
// The proxy forwards /api and /ws to the backend, so the frontend code can
// always use relative URLs ("/api/agents"). Later the backend will serve the
// built files itself, and the same relative URLs keep working.
export default defineConfig({
  plugins: [react(), tailwindcss()],
  server: {
    host: "127.0.0.1",
    port: 5173,
    proxy: {
      "/api": "http://127.0.0.1:8000",
      "/ws": { target: "ws://127.0.0.1:8000", ws: true },
    },
  },
});
